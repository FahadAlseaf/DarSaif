// ─── emit the TS data module ─────────────────────────────────────────────
import { writeFileSync } from "node:fs";
const shape = (logo, bar, x, kind) =>
  `  {\n    kind: "${kind}",\n    logo: ${fmt(logo)},\n    bar: ${fmt(bar)},\n    cross: ${fmt(x)},\n  },`;

writeFileSync(
  "components/najdi/logoMorph.ts",
  `/**
 * Geometry for the header mark's morph: logo → burger lines → ✕.
 *
 * The Dar Saif mark happens to be three shapes (crescent + two tiles) and a
 * burger is three lines, so each shape morphs into one line rather than the
 * two states crossfading. Every state of a shape is stored as a flat list of
 * x/y numbers sharing ONE command structure, so a state is just a lerp
 * between two arrays — no path-morphing library needed.
 *
 * GENERATED by \`pnpm gen:logo-morph\` — do not hand-edit. Re-run it (and edit
 * the source path/geometry in that script) if the logo artwork changes.
 * viewBox: 0 0 ${VB_W} ${VB_H} (the mark is ${Y_SHIFT}u down, leaving room for the lines).
 */

/** "crescent" = M + 7C + L + 8C + Z. "tile" = M + 3L + Z. */
export type MorphKind = "crescent" | "tile";

export interface MorphShape {
  kind: MorphKind;
  logo: number[];
  bar: number[];
  cross: number[];
}

export const VIEW_BOX = "0 0 ${VB_W} ${VB_H}";

export const MORPH_SHAPES: MorphShape[] = [
${shape(crescentLogo, bars[0], XS[0], "crescent")}
${shape(tileLogo[0], bars[1], XS[1], "tile")}
${shape(tileLogo[1], bars[2], XS[2], "tile")}
];
`
);
