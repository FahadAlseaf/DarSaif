// Generates matched path-number arrays for the logo -> burger -> ✕ morph.
// Every state of a given shape must share the SAME command structure so the
// numbers can be lerped straight through.

const VB_W = 1020, VB_H = 620;
const CX = VB_W / 2, CY = VB_H / 2;
const Y_SHIFT = (VB_H - 216) / 2; // centre the 216-tall logo in the taller box

// Burger geometry (user units; svg renders 56px wide -> scale 0.0549)
const BAR_X0 = 182, BAR_X1 = 838, BAR_T = 46;
const BAR_CY = [183, 310, 437];

const r1 = (n) => Math.round(n * 10) / 10;

// ─── Shape 0: the crescent. M + 7C + L + 8C + Z ──────────────────────────
const CRESCENT = `M0 0 C15 7.7 30.2 16.2 45 23 C59.8 29.8 73 35.2 89 41 C105 46.8 123.8 53 141 58 C158.2 63 176.2 67.3 192 71 C207.8 74.7 216 76.7 236 80 C256 83.3 279.8 87.7 312 91 C344.2 94.3 390 97 429 100 L387 205 C352.3 201.3 315.8 198.5 283 194 C250.2 189.5 215.7 183.3 190 178 C164.3 172.7 143.2 166.3 129 162 C114.8 157.7 113.7 158.8 105 152 C96.3 145.2 86.2 132.2 77 121 C67.8 109.8 58.8 97.7 50 85 C41.2 72.3 32.3 59.2 24 45 C15.7 30.8 8 15 0 0 Z`;

const crescentNums = CRESCENT.match(/-?[\d.]+/g).map(Number);
// y-shift every odd index
const crescentLogo = crescentNums.map((n, i) => (i % 2 ? r1(n + Y_SHIFT) : n));

/** Rectangle drawn with M + 7C (top edge) + L + 8C (bottom edge) + Z. */
function rectAsCrescentStructure(x0, x1, yTop, yBot) {
  const out = [x0, yTop];
  const edge = (from, to, y, segs) => {
    for (let k = 0; k < segs; k++) {
      const a = from + ((to - from) * k) / segs;
      const b = from + ((to - from) * (k + 1)) / segs;
      out.push(a + (b - a) / 3, y, a + (2 * (b - a)) / 3, y, b, y);
    }
  };
  edge(x0, x1, yTop, 7);
  out.push(x1, yBot);
  edge(x1, x0, yBot, 8);
  return out.map(r1);
}

// ─── Shapes 1 & 2: the tiles. M + 3L + Z ─────────────────────────────────
const TILES = [
  [512, 103, 698, 99, 653, 214, 470, 212],
  [798, 94, 1019, 78, 971, 201, 752, 214],
];
const tileLogo = TILES.map((t) => t.map((n, i) => (i % 2 ? r1(n + Y_SHIFT) : n)));
const rectAsTile = (x0, x1, yTop, yBot) => [x0, yTop, x1, yTop, x1, yBot, x0, yBot];

// ─── ✕ state: re-centre the bar on the svg centre, then rotate ───────────
function rotateAbout(nums, deg, cx, cy, dy) {
  const rad = (deg * Math.PI) / 180;
  const cos = Math.cos(rad), sin = Math.sin(rad);
  const out = [];
  for (let i = 0; i < nums.length; i += 2) {
    const x = nums[i], y = nums[i + 1] + dy; // slide to centre first
    out.push(
      r1(cx + (x - cx) * cos - (y - cy) * sin),
      r1(cy + (x - cx) * sin + (y - cy) * cos)
    );
  }
  return out;
}

const bars = BAR_CY.map((cy, i) => {
  const yTop = cy - BAR_T / 2, yBot = cy + BAR_T / 2;
  return i === 0
    ? rectAsCrescentStructure(BAR_X0, BAR_X1, yTop, yBot)
    : rectAsTile(BAR_X0, BAR_X1, yTop, yBot);
});

const XS = [
  rotateAbout(bars[0], 45, CX, CY, CY - BAR_CY[0]),
  // The middle line collapses into the centre point as it fades, rather than
  // lingering as a slab behind the ✕.
  bars[1].map((_, i) => (i % 2 ? CY : CX)),
  rotateAbout(bars[2], -45, CX, CY, CY - BAR_CY[2]),
];

